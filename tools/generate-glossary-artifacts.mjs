import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { allPageTermIds } from "../lib/glossary/page-profiles.mjs";
import { mathGlossaryCategories, mathGlossaryTerms, validateMathGlossary } from "../lib/glossary/math/registry.mjs";

const validationErrors = validateMathGlossary();
if (validationErrors.length) throw new Error(`Cannot generate glossary artifacts: ${validationErrors.join("; ")}`);

const categories = new Map(mathGlossaryCategories.map((category) => [category.id, category.label]));
const termById = new Map(mathGlossaryTerms.map((term) => [term.id, term]));
const missingPageTerms = allPageTermIds.filter((id) => !termById.has(id));
if (missingPageTerms.length) throw new Error(`Unknown contextual glossary terms: ${missingPageTerms.join(", ")}`);

const searchTerms = mathGlossaryTerms.map((term) => ({
  id: term.id,
  term: term.term,
  categoryLabel: categories.get(term.categoryId),
  shortDefinition: term.shortDefinition,
  aliases: term.aliases,
  keywords: term.keywords,
  visualText: term.visuals.flatMap((visual) => [visual.tex, visual.label]),
}));

const pageTerms = Object.fromEntries(allPageTermIds.map((id) => {
  const term = termById.get(id);
  return [id, {
    id: term.id,
    term: term.term,
    shortDefinition: term.shortDefinition,
    visuals: term.visuals.slice(0, 2),
  }];
}));

const banner = "// Generated by tools/generate-glossary-artifacts.mjs. Do not edit by hand.\n";
await writeFile(fileURLToPath(new URL("../lib/glossary/math/search-artifact.mjs", import.meta.url)), `${banner}export const mathGlossarySearchTerms = Object.freeze(${JSON.stringify(searchTerms)});\n`, "utf8");
await writeFile(fileURLToPath(new URL("../lib/glossary/math/page-artifact.mjs", import.meta.url)), `${banner}export const pageTermSummaries = Object.freeze(${JSON.stringify(pageTerms)});\n`, "utf8");

console.log(`Generated ${searchTerms.length} glossary search records and ${Object.keys(pageTerms).length} contextual summaries.`);
